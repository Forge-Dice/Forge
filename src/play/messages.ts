// Player-facing UI text of the CLI and the browser front end, per language. Case text (titles,
// briefs, labels, questions, evidence texts, epilogues) comes from the case's own locale variant;
// this table holds only the frame around it. German is the default; English mirrors it key by key.

export const LANGS = ["de", "en"] as const;
export type Lang = (typeof LANGS)[number];
export const DEFAULT_LANG: Lang = "de";

/** "en", "EN", "en-US" -> "en"; anything unknown -> null. */
export function parseLang(input: string | null | undefined): Lang | null {
  const code = (input ?? "").trim().toLowerCase().slice(0, 2);
  return (LANGS as readonly string[]).includes(code) ? (code as Lang) : null;
}

